/** يعيد اسم أيقونة Material Symbols للتصنيف الخام، أو أيقونة عامة عند الجهل. */
export function categoryIcon(rawCategory: string | undefined): string {
  if (!rawCategory) return 'place'
  const value = rawCategory.includes('=') ? rawCategory.split('=')[1] : rawCategory
  return VALUE_ICONS[value] ?? 'place'
}
